#!/usr/bin/env bash
# HackyPay Raspberry Pi kiosk setup
#
# Turns a Raspberry Pi OS (Bookworm or later) install into a HackyPay kiosk:
#   - boots to console (no desktop), starts X + Chromium kiosk on tty1 via systemd
#   - display forced to portrait 720x1280 (rotates X only if the panel comes up
#     landscape, and fixes the touchscreen coordinate matrix to match)
#   - thin client: points Chromium at your HackyPay backend, no code on the Pi
#
# Usage:  sudo ./setup-kiosk.sh [BACKEND_URL]
#         sudo ./setup-kiosk.sh http://192.168.1.50:8000
# Re-run any time to change the URL or repair files. Safe to run repeatedly.

set -euo pipefail

# ---------------------------------------------------------------------------
# Configuration
# ---------------------------------------------------------------------------
KIOSK_USER="kiosk"
ROTATE="${KIOSK_ROTATE:-left}"   # 'left' or 'right' — flip if the UI is upside down

log() { printf '\n==> %s\n' "$*"; }
die() { printf 'ERROR: %s\n' "$*" >&2; exit 1; }

# ---------------------------------------------------------------------------
# Preflight
# ---------------------------------------------------------------------------
[ "$(id -u)" -eq 0 ] || die "run with sudo"

if ! grep -qi 'raspberry pi' /proc/device-tree/model 2>/dev/null; then
    log "WARNING: this does not look like a Raspberry Pi — continuing anyway"
fi

BACKEND_URL="${1:-}"
if [ -z "$BACKEND_URL" ]; then
    read -r -p "HackyPay backend URL (e.g. http://192.168.1.50:8000): " BACKEND_URL
fi
[[ "$BACKEND_URL" =~ ^https?:// ]] || die "backend URL must start with http:// or https://"

case "$ROTATE" in left|right) ;; *) die "KIOSK_ROTATE must be 'left' or 'right'" ;; esac

# ---------------------------------------------------------------------------
# Packages (chromium name varies across OS releases)
# ---------------------------------------------------------------------------
log "Installing packages"
export DEBIAN_FRONTEND=noninteractive
apt-get update -qq
apt-get install -y -qq \
    xserver-xorg xinit x11-xserver-utils xinput unclutter curl ca-certificates >/dev/null

CHROMIUM_BIN=""
for candidate in chromium chromium-browser; do
    if command -v "$candidate" >/dev/null 2>&1 || apt-get install -y -qq "$candidate" >/dev/null 2>&1; then
        command -v "$candidate" >/dev/null 2>&1 && CHROMIUM_BIN="$(command -v "$candidate")" && break
    fi
done
[ -n "$CHROMIUM_BIN" ] || die "could not install chromium (check apt sources)"

# ---------------------------------------------------------------------------
# Kiosk user
# ---------------------------------------------------------------------------
log "Configuring kiosk user '$KIOSK_USER'"
id "$KIOSK_USER" >/dev/null 2>&1 || useradd --create-home --shell /bin/bash "$KIOSK_USER"
usermod -aG video,input "$KIOSK_USER"

# ---------------------------------------------------------------------------
# X session: portrait fix + touchscreen matrix + chromium watchdog
# ---------------------------------------------------------------------------
log "Writing /home/$KIOSK_USER/.xinitrc"

# Touch matrix pairs for a 90-degree X rotation (libinput Coordinate Transformation Matrix):
#   left  -> 0 -1 1 1 0 0 0 0 0
#   right -> 0 1 0 -1 0 1 0 0 0
if [ "$ROTATE" = "left" ]; then
    TOUCH_MATRIX="0 -1 1 1 0 0 0 0 0"
else
    TOUCH_MATRIX="0 1 0 -1 0 1 0 0 0"
fi

cat > "/home/$KIOSK_USER/.xinitrc" <<EOF
#!/bin/sh
# Generated by HackyPay setup-kiosk.sh — edit via the setup script, not here.

xset s off -dpms
unclutter -idle 0 &

# Portrait: rotate X only if the panel comes up landscape; align touch to match.
# On the official 7" panel the native mode is already 720x1280 and this is a no-op.
OUTPUT=\$(xrandr --query | awk '/ connected/{print \$1; exit}')
MODE=\$(xrandr --query | awk -v o="\$OUTPUT" '\$0 ~ o" connected"{for(i=1;i<=NF;i++) if (\$i ~ /^[0-9]+x[0-9]+\\+0\\+0\$/) print \$i}')
W=\${MODE%%x*}
H=\$(echo "\$MODE" | cut -d'x' -f2 | cut -d'+' -f1)
if [ -n "\$W" ] && [ "\$W" -gt "\$H" ]; then
    xrandr --output "\$OUTPUT" --rotate "$ROTATE"
    TOUCH=\$(xinput list --name-only | grep -im1 -E 'touch|ilitek|ft5x|ads78|eit|ts$')
    if [ -n "\$TOUCH" ]; then
        xinput set-prop "\$TOUCH" --type=float "Coordinate Transformation Matrix" $TOUCH_MATRIX
    fi
fi

# Wait (max 60s) for the backend before showing anything
for _ in \$(seq 1 60); do
    curl -fsS -m 2 "$BACKEND_URL/api/health" >/dev/null 2>&1 && break
    sleep 1
done

# Chromium kiosk; restart if it ever exits (crash, kill, OOM)
while :; do
    $CHROMIUM_BIN \\
        --kiosk \\
        --noerrdialogs \\
        --disable-infobars \\
        --disable-session-crashed-bubble \\
        --no-first-run \\
        --disable-crash-reporter \\
        --enable-gpu-rasterization \\
        --ignore-gpu-blocklist \\
        --overscroll-history-navigation=0 \\
        --disable-features=Translate,MediaRouter \\
        --user-data-dir=/home/$KIOSK_USER/.chromekiosk \\
        "$BACKEND_URL"
    sleep 5
done
EOF

chown "$KIOSK_USER:$KIOSK_USER" "/home/$KIOSK_USER/.xinitrc"
chmod 755 "/home/$KIOSK_USER/.xinitrc"

# ---------------------------------------------------------------------------
# systemd unit: X + kiosk on tty1, restart on failure
# ---------------------------------------------------------------------------
log "Writing /etc/systemd/system/hackypay-kiosk.service"

cat > /etc/systemd/system/hackypay-kiosk.service <<EOF
[Unit]
Description=HackyPay kiosk (X + Chromium on tty1)
After=systemd-user-sessions.service network-online.target
Wants=network-online.target
Conflicts=getty@tty1.service

[Service]
User=$KIOSK_USER
PAMName=login
WorkingDirectory=/home/$KIOSK_USER
TTYPath=/dev/tty1
TTYReset=yes
TTYVHangup=yes
StandardInput=null
StandardOutput=journal
StandardError=journal
ExecStart=/usr/bin/xinit /home/$KIOSK_USER/.xinitrc -- /usr/bin/X :0 vt1 -nolisten tcp -s 0 -dpms
Restart=always
RestartSec=5

[Install]
WantedBy=multi-user.target
EOF

# ---------------------------------------------------------------------------
# Boot policy: console target + our unit; no display manager in the way
# ---------------------------------------------------------------------------
log "Setting boot policy (console target, kiosk enabled, display managers off)"
systemctl disable lightdm gdm3 sddm 2>/dev/null || true
systemctl set-default multi-user.target
systemctl daemon-reload
systemctl enable hackypay-kiosk.service

# ---------------------------------------------------------------------------
log "Done. Summary:"
echo "  backend URL : $BACKEND_URL"
echo "  rotation    : $ROTATE (flip with: KIOSK_ROTATE=right sudo ./setup-kiosk.sh $BACKEND_URL)"
echo "  user/unit   : $KIOSK_USER / hackypay-kiosk.service (tty1)"
echo
echo "Next: sudo reboot — the Pi boots straight to the kiosk in portrait."
echo "Logs: journalctl -u hackypay-kiosk -f"
echo "If the UI is upside down, re-run with KIOSK_ROTATE=right (touch follows automatically)."