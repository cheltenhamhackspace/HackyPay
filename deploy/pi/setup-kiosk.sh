#!/usr/bin/env bash
# HackyPay Raspberry Pi kiosk setup (Wayland / labwc)
#
# Turns a Raspberry Pi OS (Bookworm or later) install into a HackyPay kiosk:
#   - autologin to the labwc Wayland session as the 'kiosk' user
#     (lightdm on desktop installs; getty autologin on Lite)
#   - Chromium kiosk pointed at the backend, respawned on crash via lwrespawn
#   - the official 7" panel is native portrait (720x1280); if the panel comes
#     up landscape it is rotated via wlr-randr — touch mapping follows
#     automatically (no coordinate matrix hacks; unclutter is X-only)
#   - thin client: points Chromium at your HackyPay backend, no code on the Pi
#
# Usage:  sudo ./setup-kiosk.sh [BACKEND_URL]
#         sudo ./setup-kiosk.sh http://10.0.2.14
#         KIOSK_ROTATE=right sudo ./setup-kiosk.sh http://10.0.2.14
# Re-run any time to change the URL or repair files. Safe to run repeatedly.
#
# The previous X11-based approach in this script does not work on current
# Raspberry Pi OS: Bookworm+ defaults to the Wayland (labwc/wlroots) stack
# and Xorg cannot take the virtual console from a systemd unit.

set -euo pipefail

# ---------------------------------------------------------------------------
# Configuration
# ---------------------------------------------------------------------------
KIOSK_USER="kiosk"
ROTATE="${KIOSK_ROTATE:-left}"   # 'left' or 'right' — flip if the UI is upside down
BACKEND_URL=""

log() { printf '\n==> %s\n' "$*"; }
die() { printf 'ERROR: %s\n' "$*" >&2; exit 1; }

# ---------------------------------------------------------------------------
# Preflight
# ---------------------------------------------------------------------------
[ "$(id -u)" -eq 0 ] || die "run with sudo"

if ! grep -qi 'raspberry pi' /proc/device-tree/model 2>/dev/null; then
    log "WARNING: this does not look like a Raspberry Pi — continuing anyway"
fi

BACKEND_URL="${1:-}"
if [ -z "$BACKEND_URL" ]; then
    read -r -p "HackyPay backend URL (e.g. http://10.0.2.14): " BACKEND_URL
fi
[[ "$BACKEND_URL" =~ ^https?:// ]] || die "backend URL must start with http:// or https://"

case "$ROTATE" in left|right) ;; *) die "KIOSK_ROTATE must be 'left' or 'right'" ;; esac

# ---------------------------------------------------------------------------
# Packages (chromium name varies across OS releases)
# ---------------------------------------------------------------------------
log "Installing packages"
export DEBIAN_FRONTEND=noninteractive
apt-get update -qq
apt-get install -y -qq curl ca-certificates wlr-randr >/dev/null

CHROMIUM_BIN=""
for candidate in chromium chromium-browser; do
    if command -v "$candidate" >/dev/null 2>&1 || apt-get install -y -qq "$candidate" >/dev/null 2>&1; then
        command -v "$candidate" >/dev/null 2>&1 && CHROMIUM_BIN="$(command -v "$candidate")" && break
    fi
done
[ -n "$CHROMIUM_BIN" ] || die "could not install chromium (check apt sources)"

# ---------------------------------------------------------------------------
# Kiosk user
# ---------------------------------------------------------------------------
log "Configuring kiosk user '$KIOSK_USER'"
id "$KIOSK_USER" >/dev/null 2>&1 || useradd --create-home --shell /bin/bash "$KIOSK_USER"
usermod -aG video,input "$KIOSK_USER"

# ---------------------------------------------------------------------------
# Clean up any previous X11-based kiosk setup (older versions of this script)
# ---------------------------------------------------------------------------
log "Removing any previous X11 kiosk config"
systemctl disable --now hackypay-kiosk.service 2>/dev/null || true
rm -f /etc/systemd/system/hackypay-kiosk.service
rm -f "/home/$KIOSK_USER/.xinitrc"
systemctl daemon-reload

# ---------------------------------------------------------------------------
# labwc autostart: optional rotation, backend wait, chromium (respawned)
# ---------------------------------------------------------------------------
log "Writing /home/$KIOSK_USER/.config/labwc/autostart"

# wlr-randr transform values: 'left' in the old X script meant 90deg CCW; the
# mapping here is simply which direction to try first when flipping.
if [ "$ROTATE" = "left" ]; then
    WLR_TRANSFORM="90"
else
    WLR_TRANSFORM="270"
fi

# lwrespawn (Raspberry Pi OS) restarts its child when it exits; fall back to a
# plain restart loop on OSes without it.
if command -v lwrespawn >/dev/null 2>&1; then
    CHROMIUM_RUN="/usr/bin/lwrespawn $CHROMIUM_BIN"
else
    CHROMIUM_RUN="while :; do $CHROMIUM_BIN"
fi

cat > "/home/$KIOSK_USER/.config/labwc/autostart" <<EOF
# Generated by HackyPay setup-kiosk.sh — edit via the setup script, not here.

# Rotate the output only if the panel comes up landscape (the official 7"
# panel is native portrait and this is a no-op). Touch mapping follows the
# output transform automatically under Wayland.
for _ in \$(seq 1 10); do
    OUT=\$(wlr-randr 2>/dev/null | awk '/^[A-Za-z]/{print \$1; exit}')
    MODE=\$(wlr-randr 2>/dev/null | awk '/px, / && /\\(current\\)/{print \$1; exit}')
    [ -n "\$MODE" ] && break
    sleep 1
done
W=\${MODE%%x*}
H=\$(echo "\$MODE" | cut -d'x' -f2 | cut -d' ' -f1)
if [ -n "\$W" ] && [ -n "\$H" ] && [ "\$W" -gt "\$H" ]; then
    wlr-randr --output "\$OUT" --transform $WLR_TRANSFORM
    sleep 1
fi

# Wait (max 60s) for the backend before starting the browser
for _ in \$(seq 1 60); do
    curl -fsS -m 2 "$BACKEND_URL/api/health" >/dev/null 2>&1 && break
    sleep 1
done

$CHROMIUM_RUN \\
    --ozone-platform=wayland \\
    --password-store=basic \\
    --kiosk \\
    --noerrdialogs \\
    --disable-infobars \\
    --disable-session-crashed-bubble \\
    --no-first-run \\
    --disable-crash-reporter \\
    --enable-gpu-rasterization \\
    --ignore-gpu-blocklist \\
    --overscroll-history-navigation=0 \\
    --disable-features=Translate,MediaRouter \\
    --user-data-dir=/home/$KIOSK_USER/.chromekiosk \\
    "$BACKEND_URL"$( [ "$CHROMIUM_RUN" = "while :; do $CHROMIUM_BIN" ] && printf ' %s\n    sleep 5\ndone' "" )
EOF

chown -R "$KIOSK_USER:$KIOSK_USER" "/home/$KIOSK_USER/.config"
chmod 644 "/home/$KIOSK_USER/.config/labwc/autostart"

# ---------------------------------------------------------------------------
# Session wiring
# ---------------------------------------------------------------------------
detect_wayland_session() {
    for s in LXDE-pi-labwc LXDE-pi-wayland labwc; do
        [ -f "/usr/share/wayland-sessions/$s.desktop" ] && { echo "$s"; return 0; }
    done
    return 1
}

WAYLAND_SESSION="$(detect_wayland_session || true)"

if [ -n "$WAYLAND_SESSION" ] && command -v lightdm >/dev/null 2>&1; then
    # Desktop install: lightdm autologin straight into the labwc session.
    log "Configuring lightdm autologin ($KIOSK_USER @ $WAYLAND_SESSION)"
    mkdir -p /etc/lightdm/lightdm.conf.d
    cat > /etc/lightdm/lightdm.conf.d/60-hackypay-kiosk.conf <<EOF
[Seat:*]
autologin-user=$KIOSK_USER
autologin-user-timeout=0
autologin-session=$WAYLAND_SESSION
EOF
    # An active autologin-user=... in the main lightdm.conf would override the
    # drop-in above (lightdm.conf is loaded last) — point it at the kiosk user.
    if grep -qE '^autologin-user=' /etc/lightdm/lightdm.conf 2>/dev/null; then
        sed -i "s/^autologin-user=.*/autologin-user=$KIOSK_USER/" /etc/lightdm/lightdm.conf
    fi
    systemctl set-default graphical.target
    systemctl enable lightdm 2>/dev/null || true
elif [ -n "$WAYLAND_SESSION" ]; then
    # Lite install: autologin getty@tty1 and exec labwc from the login shell.
    log "Configuring getty autologin ($KIOSK_USER @ tty1, labwc)"
    apt-get install -y -qq labwc >/dev/null
    mkdir -p "/etc/systemd/system/getty@tty1.service.d"
    cat > "/etc/systemd/system/getty@tty1.service.d/autologin.conf" <<EOF
[Service]
ExecStart=
ExecStart=-/sbin/agetty --autologin $KIOSK_USER --noclear %I \$TERM
EOF
    cat > "/home/$KIOSK_USER/.profile" <<'EOF'
# HackyPay kiosk: start the compositor when logging in on the console
if [ "$(tty)" = "/dev/tty1" ] && command -v labwc >/dev/null; then
    exec labwc
fi
EOF
    chown "$KIOSK_USER:$KIOSK_USER" "/home/$KIOSK_USER/.profile"
    systemctl set-default multi-user.target
    systemctl enable getty@tty1 2>/dev/null || true
else
    die "no Wayland session available — install a labwc-based Raspberry Pi OS image (Bookworm+ with desktop, or 'apt install labwc')"
fi

# ---------------------------------------------------------------------------
log "Done. Summary:"
echo "  backend URL : $BACKEND_URL"
echo "  session     : kiosk autologin -> ${WAYLAND_SESSION:-labwc} (Wayland)"
echo "  rotation    : $ROTATE (only applied if the panel is landscape; flip with: KIOSK_ROTATE=right sudo ./setup-kiosk.sh $BACKEND_URL)"
echo "  user        : $KIOSK_USER (groups: video, input)"
echo
echo "Next: sudo reboot — the Pi boots straight into the kiosk."
echo "Logs: journalctl -u lightdm -f  (or: journalctl _COMM=labwc -f)"
echo "If the UI is upside down, re-run with KIOSK_ROTATE=right."
